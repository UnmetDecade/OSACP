/**
 * Role chat and builder Shell.
 *
 * Both are ordinary scheduled tasks and do not bypass claim / lease / fencing / audit:
 *   - task.chat.<role>: hand a message to that role's Agent. When no chat-capable Agent is bound,
 *     return a deterministic role description explicitly marked mode=deterministic, without pretending it is a model reply.
 *   - task.console.builder: run full shell commands inside the builder container, equivalent to SSH.
 *     v4 removed the allowlist; isolation is handled by the container boundary, resource limits and network policy.
 */

const ROLE_PERSONA: Record<string, { name: string; duty: string; line: string }> = {
  builder: {
    name: "Tamp",
    duty: "compiling, executing, and in-container forensics",
    line: "Give me a command and I will give you a result that runs.",
  },
  scheduler: {
    name: "Relay",
    duty: "queuing, leases, and dispatch",
    line: "No guessing, no grabbing; tasks go to the builder that should run them, by the rules.",
  },
};

function roleOf(taskType: string): string {
  const role = taskType.split(".")[2] ?? "";
  return ROLE_PERSONA[role] ? role : "builder";
}

function chatOf(task: { requirements?: Record<string, unknown> }): {
  message: string;
  sessionId: string;
  history: Array<{ role: string; text: string }>;
} {
  const raw = (task.requirements?.chat ?? {}) as Record<string, unknown>;
  const message = typeof raw.message === "string" ? raw.message.slice(0, 4000) : "";
  const sessionId = typeof raw.session_id === "string" ? raw.session_id.slice(0, 120) : "";
  const history = Array.isArray(raw.history)
    ? raw.history
        .filter((h): h is Record<string, unknown> => !!h && typeof h === "object")
        .slice(-12)
        .map((h) => ({
          role: String(h.role ?? "user").slice(0, 20),
          text: String(h.text ?? "").slice(0, 2000),
        }))
    : [];
  return { message, sessionId, history };
}

/**
 * Deterministic chat: even without a usable chat Agent, give an answer that can be checked,
 * but make clear to the caller that it was not model-generated. Answers use only public fields from the task envelope.
 */
export function chatExecutorFor(role: string): Executor {
  const persona = ROLE_PERSONA[role] ?? ROLE_PERSONA.builder;
  return async (task, ctx) => {
    const { message, history } = chatOf(task);
    if (!message.trim()) {
      throw new TaskFailed("CHAT_MESSAGE_EMPTY", "Message is empty");
    }
    ctx.progress(30, "Reading role context");
    const lower = message.toLowerCase();
    const agent = task.agent?.profile_id
      ? `${task.agent.profile_id}${task.agent.version ? `@${task.agent.version}` : ""}`
      : "no Agent bound";

    let reply: string;
    if (lower.includes("agent") || message.includes("模型") || message.includes("绑定")) {
      reply = `I am ${persona.name}. This workstation is bound to ${agent}. I only see this conversation and the history explicitly passed in; I do not read other sessions in the workflow.`;
    } else if (message.includes("进度") || message.includes("状态") || message.includes("忙")) {
      reply = `This message is itself a task.chat.${role} task; check the task center for progress. ${persona.line}`;
    } else if (message.includes("ssh") || message.includes("终端") || message.includes("shell")) {
      reply =
        role === "builder"
          ? "The terminal is full SSH: root login, arbitrary commands, apt and compilation available. The address and port are in the builder details."
          : "The scheduler does not run builds; it only queues and dispatches. SSH is on the builder.";
    } else if (message.includes("磁盘") || message.includes("空间")) {
      reply = "Run df -h in the terminal to see it; it is recommended to clear the builder artifact directory weekly.";
    } else if (message.includes("你好") || lower.includes("hello") || lower.includes("hi")) {
      reply = `Hello, I am ${persona.name}, responsible for ${persona.duty}. ${persona.line}`;
    } else {
      reply = `Received. I am ${persona.name}, responsible for ${persona.duty}. No chat-capable model is currently bound, so this is a deterministic reply generated by the platform; once an Agent Profile is configured, the same task will be handed to the designated Agent.`;
    }

    ctx.progress(80, "Generating reply");
    ctx.log(`chat ${task.task_id}: mode=deterministic history=${history.length}`);
    return {
      summary: `${persona.name} reply (deterministic)`,
      outputs: {
        reply,
        mode: "deterministic",
        role,
        task_id: task.task_id,
        agent_profile_id: task.agent?.profile_id ?? null,
        history_turns: history.length,
      },
    };
  };
}

