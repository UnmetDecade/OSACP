import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { q, q1 } from "../db.js";
import { ApiError } from "../errors.js";
import { newId } from "../ids.js";

/**
 * Artifact channel (§7.8).
 *
 * Key point: on `complete` the **server recomputes SHA-256** and compares it with the digest declared by the uploader.
 * Approval binds to the digest computed by the server, not to a string the executor wrote into outputs —
 * otherwise "approve whatever is reported" makes digest verification meaningless.
 *
 * Storage is a local directory (ARTIFACT_DIR); production should use object storage + presigned URLs without changing the API semantics.
 */

const MAX_BYTES = 64 * 1024 * 1024;

export function artifactDir(): string {
  return path.resolve(process.env.ARTIFACT_DIR ?? "data/artifacts");
}

function ensureDir(): string {
  const dir = artifactDir();
  fs.mkdirSync(dir, { recursive: true });
  return dir;
}

export function normalizeDigest(value: string): string {
  const hex = value.startsWith("sha256:") ? value.slice(7) : value;
  if (!/^[0-9a-f]{64}$/i.test(hex)) {
    throw new ApiError(400, "BAD_REQUEST", "sha256 must be 64 hex characters");
  }
  return `sha256:${hex.toLowerCase()}`;
}

export function digestOf(data: Buffer): string {
  return `sha256:${createHash("sha256").update(data).digest("hex")}`;
}

export interface CreateArtifactInput {
  task_id: string;
  attempt_id?: string;
  sha256: string;
  size_bytes?: number;
  media_type?: string;
  /** Original file name (workspace-relative for collected files); metadata only, never used as a storage path. */
  name?: string;
}

/** Keep file names readable but inert: metadata only, so this does not need to reject every odd character. */
function normalizeName(value: unknown): string | null {
  const raw = String(value ?? "").replace(/\\/g, "/").trim();
  if (!raw) return null;
  const name = raw
    .replace(/[\u0000-\u001f\u007f]/g, "")
    .replace(/^\/+/, "")
    .slice(0, 300);
  return name || null;
}

export async function createArtifact(input: CreateArtifactInput, instanceId?: string) {
  if (!input.task_id) throw new ApiError(400, "BAD_REQUEST", "task_id is required");
  const declared = normalizeDigest(input.sha256);

  const task = await q1(`SELECT task_id FROM tasks WHERE task_id = $1`, [input.task_id]);
  if (!task) throw new ApiError(404, "NOT_FOUND", `task not found: ${input.task_id}`);

  let owner = instanceId;
  if (input.attempt_id) {
    const attempt = await q1<{ task_id: string; instance_id: string }>(
      `SELECT task_id, instance_id FROM task_attempts WHERE attempt_id = $1`,
      [input.attempt_id],
    );
    if (!attempt) throw new ApiError(404, "NOT_FOUND", `attempt not found: ${input.attempt_id}`);
    if (attempt.task_id !== input.task_id) {
      throw new ApiError(409, "STATE_CONFLICT", "attempt does not belong to this task");
    }
    if (instanceId && attempt.instance_id !== instanceId) {
      throw new ApiError(403, "ROLE_NOT_ALLOWED", "artifacts may only be uploaded for your own attempt");
    }
    owner = attempt.instance_id;
  }
  if (!owner) throw new ApiError(400, "BAD_REQUEST", "missing instance_id");

  const artifactId = newId("art");
  const row = (
    await q1(
      `INSERT INTO artifacts
         (artifact_id, task_id, attempt_id, instance_id, status, declared_sha256,
          size_bytes, media_type, storage_ref, name)
       VALUES ($1,$2,$3,$4,'PENDING',$5,$6,$7,$8,$9)
       RETURNING *`,
      [
        artifactId,
        input.task_id,
        input.attempt_id ?? null,
        owner,
        declared,
        input.size_bytes ?? null,
        input.media_type ?? "application/octet-stream",
        `${artifactId}.bin`,
        normalizeName(input.name),
      ],
    )
  )!;

  return {
    ...row,
    upload: {
      method: "PUT",
      path: `/v1/artifacts/${artifactId}/content`,
      complete_path: `/v1/artifacts/${artifactId}/complete`,
    },
  };
}

function storagePath(storageRef: string): string {
  // storage_ref is generated by the server (<id>.bin); external paths are not accepted
  return path.join(ensureDir(), path.basename(storageRef));
}

export async function putArtifactContent(artifactId: string, data: Buffer, instanceId?: string) {
  if (data.length > MAX_BYTES) {
    throw new ApiError(413, "PAYLOAD_TOO_LARGE", "artifact exceeds 64MB");
  }
  const row = await q1<any>(`SELECT * FROM artifacts WHERE artifact_id = $1`, [artifactId]);
  if (!row) throw new ApiError(404, "NOT_FOUND", `artifact not found: ${artifactId}`);
  if (instanceId && row.instance_id !== instanceId) {
    throw new ApiError(403, "ROLE_NOT_ALLOWED", "artifacts may only be uploaded for your own instance");
  }
  if (row.status !== "PENDING") {
    throw new ApiError(409, "STATE_CONFLICT", `artifact is already ${row.status}`);
  }

  const file = storagePath(row.storage_ref);
  const tmp = `${file}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, data);
  fs.renameSync(tmp, file);

  await q(`UPDATE artifacts SET size_bytes = $2 WHERE artifact_id = $1`, [artifactId, data.length]);
  return { artifact_id: artifactId, size_bytes: data.length };
}

export async function completeArtifact(artifactId: string, instanceId?: string) {
  const row = await q1<any>(`SELECT * FROM artifacts WHERE artifact_id = $1`, [artifactId]);
  if (!row) throw new ApiError(404, "NOT_FOUND", `artifact not found: ${artifactId}`);
  if (instanceId && row.instance_id !== instanceId) {
    throw new ApiError(403, "ROLE_NOT_ALLOWED", "artifacts may only be confirmed for your own instance");
  }

  // Idempotent: a repeated complete returns the result directly
  if (row.status === "COMPLETE") {
    return { ...row, idempotent: true };
  }
  if (row.status !== "PENDING") {
    throw new ApiError(409, "STATE_CONFLICT", `artifact is already ${row.status}`);
  }

  const file = storagePath(row.storage_ref);
  if (!fs.existsSync(file)) {
    throw new ApiError(409, "ARTIFACT_NOT_UPLOADED", "artifact content has not been uploaded");
  }
  const actual = digestOf(fs.readFileSync(file));

  if (actual !== row.declared_sha256) {
    await q(`UPDATE artifacts SET status = 'FAILED', actual_sha256 = $2 WHERE artifact_id = $1`, [
      artifactId,
      actual,
    ]);
    throw new ApiError(422, "ARTIFACT_DIGEST_MISMATCH", "artifact content does not match the declared digest", {
      declared: row.declared_sha256,
      actual,
    });
  }

  const updated = await q1(
    `UPDATE artifacts
        SET status = 'COMPLETE', actual_sha256 = $2, completed_at = app_now()
      WHERE artifact_id = $1
      RETURNING *`,
    [artifactId, actual],
  );
  return updated;
}

export async function getArtifact(artifactId: string) {
  const row = await q1(`SELECT * FROM artifacts WHERE artifact_id = $1`, [artifactId]);
  if (!row) throw new ApiError(404, "NOT_FOUND", `artifact not found: ${artifactId}`);
  return row;
}

/**
 * Files produced by one task.
 *
 * This is the operator-facing side of the file channel: task detail pages and sideload clients list a
 * task's files here, then fetch bytes from the download route. Only COMPLETE artifacts are downloadable;
 * PENDING and FAILED rows still appear so a client can tell "not uploaded yet" from "never declared".
 */
export async function listTaskArtifacts(taskId: string) {
  const task = await q1(`SELECT task_id FROM tasks WHERE task_id = $1`, [taskId]);
  if (!task) throw new ApiError(404, "NOT_FOUND", `task not found: ${taskId}`);
  return q(
    `SELECT artifact_id, task_id, attempt_id, instance_id, status, name, media_type,
            size_bytes, declared_sha256, actual_sha256, created_at, completed_at
       FROM artifacts
      WHERE task_id = $1
      ORDER BY created_at, artifact_id`,
    [taskId],
  );
}

/** A human file name for Content-Disposition: the recorded name's basename, else the artifact id plus a media-type extension. */
export function downloadFilename(row: {
  artifact_id: string;
  name?: string | null;
  media_type?: string | null;
}): string {
  const base = String(row.name ?? "")
    .split("/")
    .filter(Boolean)
    .pop();
  if (base) return base;
  const type = String(row.media_type ?? "").toLowerCase();
  const ext = type === "application/json" ? ".json"
    : type === "text/plain" ? ".txt"
    : type === "text/markdown" ? ".md"
    : type === "application/pdf" ? ".pdf"
    : type === "image/png" ? ".png"
    : type === "image/jpeg" ? ".jpg"
    : type === "application/zip" ? ".zip"
    : type === "application/gzip" ? ".gz"
    : ".bin";
  return `${row.artifact_id}${ext}`;
}

/**
 * Read artifact contents.
 *
 * There are only two authorization paths:
 *   1) the caller is the instance that owns the artifact;
 *   2) the caller is on an in-progress attempt, and that task's `requirements.upstream_artifacts`
 *      references this artifact — i.e. explicitly handed over by the scheduler during workflow advance.
 * Do not relax this by task, by role, or on the grounds of "it's the same workflow".
 * An empty `instanceId` only happens in local development without auth configured.
 */
export async function readArtifactContent(artifactId: string, instanceId?: string) {
  const row = await q1<any>(`SELECT * FROM artifacts WHERE artifact_id = $1`, [artifactId]);
  if (!row) throw new ApiError(404, "NOT_FOUND", `artifact not found: ${artifactId}`);
  if (row.status !== "COMPLETE") {
    throw new ApiError(409, "STATE_CONFLICT", `artifact has not passed verification: ${row.status}`);
  }

  if (instanceId && row.instance_id !== instanceId) {
    const allowed = await q1(
      `SELECT 1
         FROM task_attempts a
         JOIN tasks t ON t.task_id = a.task_id
        WHERE a.instance_id = $2
          AND a.status IN ('CREATED','STARTED')
          AND EXISTS (
            SELECT 1
              FROM jsonb_array_elements(
                     COALESCE(t.requirements->'upstream_artifacts', '[]'::jsonb)) e
             WHERE e->>'artifact_id' = $1)
        LIMIT 1`,
      [artifactId, instanceId],
    );
    if (!allowed) {
      throw new ApiError(403, "ROLE_NOT_ALLOWED", "you may only read artifacts of your own instance, or upstream artifacts handed to the current task by the scheduler");
    }
  }

  const file = storagePath(row.storage_ref);
  if (!fs.existsSync(file)) throw new ApiError(409, "ARTIFACT_NOT_UPLOADED", "artifact content does not exist");
  return {
    artifact_id: row.artifact_id,
    name: row.name ?? null,
    media_type: row.media_type ?? "application/octet-stream",
    sha256: row.actual_sha256,
    data: fs.readFileSync(file),
  };
}

/** The most recent verified artifact of a task — this is the value the approval digest uses */
export async function latestCompleteArtifact(taskId: string) {
  return q1<{ artifact_id: string; actual_sha256: string; size_bytes: number | null }>(
    `SELECT artifact_id, actual_sha256, size_bytes FROM artifacts
      WHERE task_id = $1 AND status = 'COMPLETE'
      ORDER BY completed_at DESC, artifact_id DESC LIMIT 1`,
    [taskId],
  );
}
